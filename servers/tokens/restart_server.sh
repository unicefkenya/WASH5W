#!/bin/bash

# ------------------------------------------------------------------------
# INITIALIZE PATH VARIABLES
# ------------------------------------------------------------------------
BASEDIR="$( cd "$( dirname "$0" )" && pwd )"


# -------------------------------------------------------------------------------------
# SET WORKING DIRECTORY
# -------------------------------------------------------------------------------------
cd $BASEDIR


# -------------------------------------------------------------------------------------
# STOP THE SERVER
# -------------------------------------------------------------------------------------

echo
echo "Stopping Tokens Server"
pm2 stop tokens

echo
echo "Deleting Tokens Server"
pm2 delete tokens

echo
echo "Starting Tokens Server"
pm2 start server.js --name "tokens"
