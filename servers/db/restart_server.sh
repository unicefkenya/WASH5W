#!/bin/bash

# ------------------------------------------------------------------------
# INITIALIZE PATH VARIABLES
# ------------------------------------------------------------------------
BASEDIR="$( cd "$( dirname "$0" )" && pwd )"


# -------------------------------------------------------------------------------------
# SET WORKING DIRECTORY
# -------------------------------------------------------------------------------------
cd $BASEDIR


# -------------------------------------------------------------------------------------
# STOP THE SERVER
# -------------------------------------------------------------------------------------

echo
echo "Stopping DB Server"
pm2 stop db

echo
echo "Deleting DB Server"
pm2 delete db

echo
echo "Starting DB Server"
pm2 start server.js --name "db"
