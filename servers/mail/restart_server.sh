#!/bin/bash

# ------------------------------------------------------------------------
# INITIALIZE PATH VARIABLES
# ------------------------------------------------------------------------
BASEDIR="$( cd "$( dirname "$0" )" && pwd )"


# -------------------------------------------------------------------------------------
# SET WORKING DIRECTORY
# -------------------------------------------------------------------------------------
cd $BASEDIR


# -------------------------------------------------------------------------------------
# STOP THE SERVER
# -------------------------------------------------------------------------------------

echo
echo "Stopping Mail Server"
pm2 stop mail

echo
echo "Deleting Mail Server"
pm2 delete mail

echo
echo "Starting Mail Server"
pm2 start server.js --name "mail"
