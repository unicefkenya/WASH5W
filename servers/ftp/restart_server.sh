#!/bin/bash

# ------------------------------------------------------------------------
# INITIALIZE PATH VARIABLES
# ------------------------------------------------------------------------
BASEDIR="$( cd "$( dirname "$0" )" && pwd )"


# -------------------------------------------------------------------------------------
# SET WORKING DIRECTORY
# -------------------------------------------------------------------------------------
cd $BASEDIR


# -------------------------------------------------------------------------------------
# STOP THE SERVER
# -------------------------------------------------------------------------------------

echo
echo "Stopping FTP Server"
pm2 stop ftp

echo
echo "Deleting FTP Server"
pm2 delete ftp

echo
echo "Starting FTP Server"
pm2 start server.js --name "ftp"
